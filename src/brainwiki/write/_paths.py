"""Paths agents hand in: made brain-relative, and checked against the files nobody edits directly."""

from __future__ import annotations

from pathlib import Path
from typing import TYPE_CHECKING

from brainwiki.errors import UsageError

if TYPE_CHECKING:
    from brainwiki.engine import Engine

_PROTECTED_FILES = ("rules.md", "log.md", "brain.toml", "AGENTS.md")


def brain_path(engine: Engine, raw: str) -> str:
    """A brain-relative path from a relative or absolute one; never outside the brain."""
    text = raw.strip()
    if not text:
        raise UsageError("empty path")
    candidate = Path(text).expanduser()
    root = engine.brain.root
    if candidate.is_absolute():
        try:
            rel = candidate.resolve().relative_to(root)
        except ValueError:
            raise UsageError(f"{raw} is outside the brain at {root}") from None
        text = rel.as_posix()
    text = text.removeprefix("./")
    if text.startswith("../") or "/../" in text or text == "..":
        raise UsageError(f"{raw} is outside the brain")
    return text


def protected_reason(engine: Engine, rel: str) -> str | None:
    """Why `rel` is never edited directly, or None for notes and hubs."""
    layout = engine.manifest.layout
    if rel in _PROTECTED_FILES:
        return f"{rel} is never edited directly"
    for folder, reason in (
        (layout.inbox_dir, "inbox files (episodes and proposals) are never edited directly"),
        (layout.archive_dir, "the archive is never edited directly"),
        (layout.reports_dir, "reports are regenerated by brain-wiki, never edited directly"),
    ):
        if rel.startswith(folder + "/"):
            return reason
    return None
