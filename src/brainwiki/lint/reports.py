"""`reports/`: index queries rendered as Markdown pages for people (design doc 06 §7)."""

from __future__ import annotations

from collections import defaultdict
from datetime import UTC, datetime
from typing import TYPE_CHECKING

from brainwiki.ids import is_ulid, ulid_datetime
from brainwiki.lint.model import LintResult

if TYPE_CHECKING:
    from brainwiki.engine import Engine

HEADER = "<!-- Generated by brain-wiki. Do not edit: `brain report` rewrites this file. -->"
REPORTS = (
    "index",
    "contradictions",
    "stale",
    "unverified",
    "inbox",
    "duplicates",
    "orphans",
    "lint",
)


def _link(path: str, title: str | None = None) -> str:
    target = path[:-3] if path.lower().endswith(".md") else path
    label = (title or "").replace("|", "/").replace("]", ")")
    return f"[[{target}|{label}]]" if label and label != target else f"[[{target}]]"


def _page(title: str, intro: str, lines: list[str], empty: str) -> str:
    body = lines or [empty]
    return "\n".join([HEADER, f"# {title}", "", intro, "", *body]) + "\n"


def contradictions(engine: Engine) -> str:
    seen: set[frozenset[str]] = set()
    lines = []
    for row in engine.db.execute(
        """SELECT a.id AS a_id, a.path AS a_path, a.title AS a_title, b.id AS b_id, b.path AS b_path,
                  b.title AS b_title, e.qualifier, e.note, e.attrs
           FROM edges e JOIN nodes a ON a.id = e.src JOIN nodes b ON b.id = e.dst
           WHERE e.rel = 'conflicts_with' AND a.status = 'active' AND b.status = 'active'
           ORDER BY a.path, b.path"""
    ):
        pair = frozenset((row["a_id"], row["b_id"]))
        if pair in seen:
            continue
        seen.add(pair)
        extra = " ".join(
            bit
            for bit in (
                f"({row['qualifier']})" if row["qualifier"] else "",
                f"— {row['note']}" if row["note"] else "",
            )
            if bit
        )
        lines.append(
            f"- {_link(row['a_path'], row['a_title'])} ↔ {_link(row['b_path'], row['b_title'])} {extra}".rstrip()
        )
    return _page(
        "Contradictions",
        "Active notes that conflict with each other. Read both before acting on either.",
        lines,
        "No open contradictions.",
    )


def stale(engine: Engine) -> str:
    lines = [
        f"- {_link(r['a_path'], r['a_title'])} depends on {_link(r['b_path'], r['b_title'])} ({r['status']})"
        for r in engine.db.execute(
            """SELECT a.path AS a_path, a.title AS a_title, b.path AS b_path, b.title AS b_title, b.status
               FROM edges e JOIN nodes a ON a.id = e.src JOIN nodes b ON b.id = e.dst
               WHERE e.rel = 'depends_on' AND a.status = 'active' AND b.status IN ('superseded', 'archived')
               ORDER BY a.path"""
        )
    ]
    return _page(
        "Stale dependencies",
        "Active notes that depend on superseded or archived notes; they may need updating.",
        lines,
        "No stale dependencies.",
    )


def unverified(engine: Engine) -> str:
    lines = [
        f"- {_link(r['path'], r['title'])}: {r['c']} unverified claim{'s' if r['c'] != 1 else ''}"
        for r in engine.db.execute(
            """SELECT n.path, n.title, COUNT(*) AS c FROM claims c JOIN nodes n ON n.id = c.node_id
               WHERE c.taint IN ('true', 'unknown') AND c.status = 'active'
               GROUP BY n.id ORDER BY c DESC, n.path"""
        )
    ]
    return _page(
        "Unverified claims",
        "Notes with active claims derived from untrusted or unknown sources (shown as [unverified] in reads).",
        lines,
        "No unverified claims.",
    )


def inbox(engine: Engine) -> str:
    now = datetime.now(UTC)
    by_agent: dict[str, list[tuple[float, str]]] = defaultdict(list)
    for row in engine.db.execute("SELECT path, fm_id, agent FROM nodes WHERE kind = 'episode'"):
        age = (
            (now - ulid_datetime(row["fm_id"])).total_seconds() / 86400
            if is_ulid(row["fm_id"] or "")
            else 0.0
        )
        by_agent[row["agent"] or "unknown"].append((age, row["path"]))
    lines = ["## Pending episodes", ""]
    if not by_agent:
        lines.append("None.")
    for agent, items in sorted(by_agent.items()):
        items.sort(reverse=True)
        lines.append(f"- **{agent}**: {len(items)} pending, oldest {items[0][0]:.0f} days")
        for age, path in items[:20]:
            lines.append(f"  - {_link(path)} ({age:.0f} days)")
        if len(items) > 20:
            lines.append(f"  - … {len(items) - 20} more")
    lines += ["", "## Open proposals", ""]
    proposals = [
        r["path"]
        for r in engine.db.execute("SELECT path FROM files WHERE kind = 'proposal' ORDER BY path")
    ]
    lines += [f"- {_link(p)}" for p in proposals] or ["None."]
    return _page(
        "Inbox", "Episodes waiting for consolidation, and proposals waiting for review.", lines, ""
    )


def duplicates(result: LintResult) -> str:
    lines = [
        f"- {_link(p.path)} line {p.line}: {p.message}"
        for p in result.problems
        if p.code == "BW206"
    ]
    return _page(
        "Duplicate claims",
        "Claims that cite the same source span with near-identical text, usually from consolidating twice.",
        lines,
        "No duplicates.",
    )


def orphans(engine: Engine) -> str:
    lines = [
        f"- {_link(r['path'], r['title'])}"
        for r in engine.db.execute(
            """SELECT n.path, n.title FROM nodes n WHERE n.kind = 'note' AND NOT EXISTS (
                 SELECT 1 FROM edges e WHERE e.other = n.id AND e.declared_in != n.id)
               ORDER BY n.path"""
        )
    ]
    return _page("Orphans", "Notes nothing links to and no hub lists.", lines, "No orphans.")


def lint_page(result: LintResult) -> str:
    lines = []
    current = None
    for p in result.problems:
        if p.path != current:
            lines.append(f"- {_link(p.path) if p.path.endswith('.md') else '`' + p.path + '`'}")
            current = p.path
        where = f"line {p.line}: " if p.line else ""
        lines.append(f"  - {p.severity} {p.code}: {where}{p.message}")
    intro = (
        f"{result.errors} errors, {result.count('warning')} warnings, {result.count('info')} info."
    )
    return _page("Lint", intro, lines, "No problems.")


def index_page(engine: Engine, result: LintResult) -> str:
    conn = engine.db

    def count(sql: str) -> int:
        return int(conn.execute(sql).fetchone()[0])

    stats = [
        ("Notes", count("SELECT COUNT(*) FROM nodes WHERE kind = 'note'")),
        ("Hubs", count("SELECT COUNT(*) FROM nodes WHERE kind = 'hub'")),
        ("Active claims", count("SELECT COUNT(*) FROM claims WHERE status = 'active'")),
        ("Relations", count("SELECT COUNT(*) FROM edges WHERE rel != 'links_to'")),
        ("Pending episodes", count("SELECT COUNT(*) FROM nodes WHERE kind = 'episode'")),
        ("Archived episodes", count("SELECT COUNT(*) FROM nodes WHERE kind = 'archived_episode'")),
    ]
    last = "never"
    try:
        for line in engine.store.read_text("log.md").splitlines():
            if line.startswith("## ") and "· consolidate ·" in line:
                last = line[3:].split(" · ")[0]
    except OSError:
        pass
    lines = [f"- {name}: {value}" for name, value in stats]
    lines += [
        f"- Last consolidation: {last}",
        f"- Lint: {result.errors} errors, {result.count('warning')} warnings",
        "",
        "## Reports",
        "",
    ]
    lines += [
        f"- [[{engine.manifest.layout.reports_dir}/{name}|{name.title()}]]"
        for name in REPORTS
        if name != "index"
    ]
    generated = datetime.now(UTC).replace(microsecond=0).isoformat().replace("+00:00", "Z")
    return _page(f"Brain report: {engine.brain.display_name}", f"Generated {generated}.", lines, "")


def generate(engine: Engine, result: LintResult | None = None) -> list[str]:
    """Rewrite every report whose content changed. Returns the paths written."""
    from brainwiki.lint.runner import lint

    result = result or lint(engine)
    pages = {
        "contradictions": contradictions(engine),
        "stale": stale(engine),
        "unverified": unverified(engine),
        "inbox": inbox(engine),
        "duplicates": duplicates(result),
        "orphans": orphans(engine),
        "lint": lint_page(result),
    }
    written = []
    directory = engine.manifest.layout.reports_dir
    for name, content in pages.items():
        rel = f"{directory}/{name}.md"
        if engine.store.exists(rel) and engine.store.read_text(rel) == content:
            continue
        engine.store.write_text(rel, content)
        written.append(rel)
    index_rel = f"{directory}/index.md"
    engine.store.write_text(index_rel, index_page(engine, result))
    written.append(index_rel)
    return written
