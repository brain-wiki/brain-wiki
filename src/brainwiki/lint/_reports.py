"""`reports/`: index queries rendered as Markdown pages for people (lint-and-reports.md §7)."""

from __future__ import annotations

from collections import defaultdict
from datetime import UTC, datetime
from typing import TYPE_CHECKING, Any

from brainwiki.ids import is_ulid, ulid_datetime
from brainwiki.lint._model import LintResult

if TYPE_CHECKING:
    from brainwiki.engine import Engine

_HEADER = "<!-- Generated by brain-wiki. Do not edit: `brain report` rewrites this file. -->"
_REPORTS = ("index", "stale", "inbox", "consolidation", "orphans", "lint")
_MAX_RUNS = 20


def _link(path: str, title: str | None = None) -> str:
    target = path[:-3] if path.lower().endswith(".md") else path
    label = (title or "").replace("|", "/").replace("]", ")")
    return f"[[{target}|{label}]]" if label and label != target else f"[[{target}]]"


def _page(title: str, intro: str, lines: list[str], empty: str) -> str:
    body = lines or [empty]
    return "\n".join([_HEADER, f"# {title}", "", intro, "", *body]) + "\n"


def _stale(engine: Engine) -> str:
    from brainwiki.index import open_conflicts, stale_dependents, stale_links

    def pair(r: Any, verb: str) -> str:
        return (
            f"- {_link(r['src_path'], r['src_title'])} {verb} "
            f"{_link(r['dst_path'], r['dst_title'])} ({r['dst_status']})"
        )

    sections = [
        (
            "Dependents",
            "Active notes that rest (`bw-depends_on`) on a superseded or archived note. Review "
            "each: does it still hold?",
            [pair(r, "depends on") for r in stale_dependents(engine.db)],
        ),
        (
            "Open conflicts",
            "Active notes that conflict (`bw-conflicts_with`). Decide which holds and supersede "
            "the other, or keep both and say why.",
            [
                f"- {_link(r['a_path'], r['a_title'])} conflicts with "
                f"{_link(r['b_path'], r['b_title'])}"
                for r in open_conflicts(engine.db)
            ],
        ),
        (
            "Stale links",
            "Active notes that link to superseded or archived notes other than the ones they "
            "replaced; they may need updating.",
            [pair(r, "links to") for r in stale_links(engine.db)],
        ),
    ]
    lines: list[str] = []
    for heading, intro, items in sections:
        lines += [f"## {heading}", "", intro, "", *(items or ["None."]), ""]
    return _page("Needs review", "Notes that may be out of date or contradict another.", lines, "")


def _inbox(engine: Engine) -> str:
    now = datetime.now(UTC)
    by_agent: dict[str, list[tuple[float, str]]] = defaultdict(list)
    for row in engine.db.execute("SELECT path, fm_id, agent FROM nodes WHERE kind = 'episode'"):
        age = (
            (now - ulid_datetime(row["fm_id"])).total_seconds() / 86400
            if is_ulid(row["fm_id"] or "")
            else 0.0
        )
        by_agent[row["agent"] or "unowned"].append((age, row["path"]))
    lines = ["## Pending episodes", ""]
    if not by_agent:
        lines.append("None.")
    for agent, items in sorted(by_agent.items()):
        items.sort(reverse=True)
        lines.append(f"- **{agent}**: {len(items)} pending, oldest {items[0][0]:.0f} days")
        for age, path in items[:20]:
            lines.append(f"  - {_link(path)} ({age:.0f} days)")
        if len(items) > 20:
            lines.append(f"  - … {len(items) - 20} more")
    lines += ["", "## Open proposals", ""]
    proposals = [
        r["path"]
        for r in engine.db.execute("SELECT path FROM files WHERE kind = 'proposal' ORDER BY path")
    ]
    lines += [f"- {_link(p)}" for p in proposals] or ["None."]
    return _page(
        "Inbox", "Episodes waiting for consolidation, and proposals waiting for review.", lines, ""
    )


def _consolidation(engine: Engine) -> str:
    from brainwiki.index import consolidation_runs, scheduled_runs

    lines: list[str] = []
    scheduled = scheduled_runs(engine)
    if scheduled:
        lines += ["", "## Scheduled runs on this machine", ""]
        for host, run in sorted(scheduled.items()):
            detail = run.get("error") if run.get("status") == "failed" else run.get("summary")
            lines.append(
                f"- **{host}** {run.get('at')}: {run.get('status')}"
                + (f", {detail}" if detail else "")
            )
    for run in reversed(consolidation_runs(engine)[-_MAX_RUNS:]):
        lines += ["", f"## {run['at']} · {run['agent'] or 'owner'} · {run['run']}", ""]
        lines.append(run["summary"] or "(no summary)")
        lines += [f"- {line}" for line in run["lines"]]
    return _page(
        "Consolidation",
        "Recent consolidation runs, newest first: what came of each episode. Review a run with "
        "`git show` on its commit, and undo it with `brain undo RUN`.",
        lines,
        "No consolidation yet.",
    )


def _orphans(engine: Engine) -> str:
    lines = [
        f"- {_link(r['path'], r['title'])}"
        for r in engine.db.execute(
            """SELECT n.path, n.title FROM nodes n WHERE n.kind = 'note' AND NOT EXISTS (
                 SELECT 1 FROM edges e WHERE e.other = n.id AND e.declared_in != n.id)
               ORDER BY n.path"""
        )
    ]
    return _page("Orphans", "Notes nothing links to and no topic page lists.", lines, "No orphans.")


def _lint_page(result: LintResult) -> str:
    lines = []
    current = None
    for p in result.problems:
        if p.path != current:
            lines.append(f"- {_link(p.path) if p.path.endswith('.md') else '`' + p.path + '`'}")
            current = p.path
        where = f"line {p.line}: " if p.line else ""
        lines.append(f"  - {p.severity} {p.code}: {where}{p.message}")
    intro = (
        f"{result.errors} errors, {result.count('warning')} warnings, {result.count('info')} info."
    )
    return _page("Lint", intro, lines, "No problems.")


def _index_page(engine: Engine, result: LintResult) -> str:
    conn = engine.db

    def count(sql: str) -> int:
        return int(conn.execute(sql).fetchone()[0])

    stats = [
        ("Notes", count("SELECT COUNT(*) FROM nodes WHERE kind = 'note'")),
        ("Topic pages", count("SELECT COUNT(*) FROM nodes WHERE kind = 'topic'")),
        ("Links", count("SELECT COUNT(*) FROM edges WHERE rel = 'links_to'")),
        ("Pending episodes", count("SELECT COUNT(*) FROM nodes WHERE kind = 'episode'")),
        ("Archived episodes", count("SELECT COUNT(*) FROM nodes WHERE kind = 'archived_episode'")),
    ]
    last = "never"
    try:
        for line in engine.store.read_text("log.md").splitlines():
            if line.startswith("## ") and "· consolidate ·" in line:
                last = line[3:].split(" · ")[0]
    except OSError:
        pass
    lines = [f"- {name}: {value}" for name, value in stats]
    lines += [
        f"- Last consolidation: {last}",
        f"- Lint: {result.errors} errors, {result.count('warning')} warnings",
        "",
        "## Reports",
        "",
    ]
    lines += [
        f"- [[{engine.manifest.layout.reports_dir}/{name}|{name.title()}]]"
        for name in _REPORTS
        if name != "index"
    ]
    generated = datetime.now(UTC).replace(microsecond=0).isoformat().replace("+00:00", "Z")
    return _page(f"Brain report: {engine.brain.display_name}", f"Generated {generated}.", lines, "")


def generate(engine: Engine, result: LintResult | None = None) -> list[str]:
    """Rewrite every report whose content changed. Returns the paths written."""
    from brainwiki.lint._runner import lint

    result = result or lint(engine)
    pages = {
        "stale": _stale(engine),
        "inbox": _inbox(engine),
        "consolidation": _consolidation(engine),
        "orphans": _orphans(engine),
        "lint": _lint_page(result),
    }
    written = []
    directory = engine.manifest.layout.reports_dir
    for name, content in pages.items():
        rel = f"{directory}/{name}.md"
        if engine.store.exists(rel) and engine.store.read_text(rel) == content:
            continue
        engine.store.write_text(rel, content)
        written.append(rel)
    index_rel = f"{directory}/index.md"
    engine.store.write_text(index_rel, _index_page(engine, result))
    written.append(index_rel)
    return written
